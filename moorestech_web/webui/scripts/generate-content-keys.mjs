import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parseRecords } from "./localizationCsvRecords.mjs";

const COLUMN_COUNT = 3;
const KEY_SEGMENT_PATTERN = /^[a-z][A-Za-z0-9]*$/;

export function parseContentKeyCatalog(text) {
  // C#共通parserと同じレコード境界と列契約を適用する
  // Apply the same record boundaries and column contract as the shared C# parser
  const records = parseRecords(text);
  if (records.length === 0) {
    throw new Error("content_keys.csv is empty");
  }

  const header = records[0];
  if (
    header.length !== COLUMN_COUNT ||
    header[0] !== "namespace" ||
    header[1] !== "field" ||
    header[2] !== "sourceMaster"
  ) {
    throw new Error(
      "content_keys.csv header must contain namespace, field, and sourceMaster columns",
    );
  }

  const definitions = [];
  const seenKeys = new Set();
  for (let recordIndex = 1; recordIndex < records.length; recordIndex += 1) {
    const fields = records[recordIndex];
    if (fields.length !== COLUMN_COUNT) {
      throw new Error(
        `Column count mismatch in content_keys.csv at record ${recordIndex + 1}: expected ${COLUMN_COUNT}, got ${fields.length}`,
      );
    }

    // キーsegmentは辞書側と同じlowerCamel契約を課す
    // Require the same lower-camel segment contract as the dictionary side
    const [contentNamespace, field, sourceMaster] = fields;
    if (!KEY_SEGMENT_PATTERN.test(contentNamespace) || !KEY_SEGMENT_PATTERN.test(field)) {
      throw new Error(
        `Content key segments '${contentNamespace}' and '${field}' must match [a-z][A-Za-z0-9]*`,
      );
    }

    if (sourceMaster.trim().length === 0) {
      throw new Error(
        `Content key '${contentNamespace}.${field}' must declare the Master that supplies its source text`,
      );
    }

    if (seenKeys.has(`${contentNamespace}.${field}`)) {
      throw new Error(`Duplicated content key: ${contentNamespace}.${field}`);
    }

    seenKeys.add(`${contentNamespace}.${field}`);
    definitions.push({ namespace: contentNamespace, field, sourceMaster });
  }

  return definitions;
}

export function generateContentKeysSource(definitions) {
  // 宣言表の全行をtemplate literal unionと型付きビルダーへ写す
  // Map every declaration row to a template literal union and typed builders
  const unionMembers = definitions.map(
    (definition) => `  | \`${definition.namespace}.\${string}.${definition.field}\``,
  );
  const builders = definitions.map((definition) => [
    `// source text: ${definition.sourceMaster}`,
    `export const ${toBuilderName(definition)} = (guid: string): ContentLocalizationKey =>`,
    `  \`${definition.namespace}.\${canonicalGuidSegment(guid)}.${definition.field}\`;`,
  ].join("\n"));

  return [
    "// generated by scripts/generate-content-keys.mjs — DO NOT EDIT",
    `export type ContentLocalizationKey =\n${unionMembers.join("\n")};`,
    "",
    builders.join("\n"),
    "",
    "function canonicalGuidSegment(guid: string): string {",
    "  return guid.toLowerCase();",
    "}",
    "",
  ].join("\n");
}

function toBuilderName(definition) {
  return `${definition.namespace}${toPascalCase(definition.field)}Key`;
}

function toPascalCase(segment) {
  return segment[0].toUpperCase() + segment.slice(1);
}

const isCli = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isCli) {
  const csvUrl = new URL("../../../Localization/content_keys.csv", import.meta.url);
  const outputUrl = new URL("../src/shared/i18n/generated/contentKeys.ts", import.meta.url);
  mkdirSync(new URL("../src/shared/i18n/generated/", import.meta.url), { recursive: true });
  writeFileSync(outputUrl, generateContentKeysSource(parseContentKeyCatalog(readFileSync(csvUrl, "utf8"))));
}
