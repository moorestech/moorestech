import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const LANGUAGE_START_COLUMN = 2;
const KEY_SEGMENT_PATTERN = /^[a-z][A-Za-z0-9]*$/;

export function parseLocalizationCsv(text) {
  // C#共通parserと同じレコード境界と列契約を適用する
  // Apply the same record boundaries and column contract as the shared C# parser
  const records = parseRecords(text);
  if (records.length === 0) {
    throw new Error("localization.csv is empty");
  }

  const header = records[0];
  if (header.length < LANGUAGE_START_COLUMN) {
    throw new Error("localization.csv header must contain key and Source columns");
  }

  const languageCodes = header.slice(LANGUAGE_START_COLUMN);
  const rows = [];
  const seenKeys = new Set();
  for (let recordIndex = 1; recordIndex < records.length; recordIndex += 1) {
    const fields = records[recordIndex];
    if (fields.length !== header.length) {
      throw new Error(
        `Column count mismatch at record ${recordIndex + 1}: expected ${header.length}, got ${fields.length}`,
      );
    }

    // キー重複をCSV入力境界で拒否し空fieldはそのまま保持する
    // Reject duplicate keys at the CSV boundary while preserving empty fields
    const key = fields[0];
    if (seenKeys.has(key)) {
      throw new Error(`Duplicated key: ${key}`);
    }

    seenKeys.add(key);
    rows.push({
      key,
      source: convertEscapedNewlines(fields[1]),
      texts: fields.slice(LANGUAGE_START_COLUMN).map(convertEscapedNewlines),
    });
  }

  return { languageCodes, rows };
}

export function generateLocalizationKeysSource(csv) {
  const root = buildKeyTree(csv.rows);
  const objectSource = emitObject(root.children);
  const keys = csv.rows.map((row) => JSON.stringify(row.key));

  // 実行時の外部キー検証にも使えるタプルからunion型を導出する
  // Derive the union from a tuple that also validates external keys at runtime
  return [
    "// generated by scripts/generate-localization-keys.mjs — DO NOT EDIT",
    `export const L = ${objectSource} as const;`,
    "",
    `export const VanillaLocalizationKeys = [${keys.join(", ")}] as const;`,
    "export type VanillaLocalizationKey = typeof VanillaLocalizationKeys[number];",
    "",
  ].join("\n");
}

function parseRecords(text) {
  const records = [];
  let fields = [];
  let field = "";
  let inQuotes = false;
  let closedQuote = false;
  let recordHasSyntax = false;

  // 文字単位の状態遷移でquote内のカンマ・改行・二重quoteを扱う
  // Use character-level transitions for quoted commas, newlines, and doubled quotes
  for (let index = 0; index < text.length; index += 1) {
    const character = text[index];
    if (inQuotes) {
      if (character !== '"') {
        field += character;
      } else if (index + 1 < text.length && text[index + 1] === '"') {
        field += '"';
        index += 1;
      } else {
        inQuotes = false;
        closedQuote = true;
      }
      continue;
    }

    // 閉じquote後はfield境界以外を不正入力として拒否する
    // Reject anything except a field boundary after a closing quote
    if (closedQuote) {
      if (character === ",") {
        addField();
        closedQuote = false;
      } else if (character === "\r" || character === "\n") {
        addRecord();
        if (character === "\r" && text[index + 1] === "\n") index += 1;
        closedQuote = false;
      } else {
        throw new Error("Unexpected character after closing quote");
      }
      continue;
    }

    if (character === '"') {
      recordHasSyntax = true;
      if (field.length !== 0) throw new Error("Quote must begin at the start of a field");
      inQuotes = true;
    } else if (character === ",") {
      addField();
    } else if (character === "\r" || character === "\n") {
      addRecord();
      if (character === "\r" && text[index + 1] === "\n") index += 1;
    } else {
      field += character;
    }
  }

  if (inQuotes) throw new Error("Unterminated quoted field");
  if (closedQuote || field.length > 0 || fields.length > 0) addRecord();
  return records;

  function addField() {
    fields.push(field);
    field = "";
  }

  function addRecord() {
    addField();
    if (fields.length > 1 || fields[0].length > 0 || recordHasSyntax) records.push(fields);
    fields = [];
    recordHasSyntax = false;
  }
}

function buildKeyTree(rows) {
  const root = createNode("", "");
  for (const row of rows) {
    const segments = row.key.split(".");
    let node = root;
    for (const segment of segments) {
      validateKeySegment(segment, row.key);
      if (node.isLeaf) throw new Error(`Key '${node.fullKey}' is both a leaf and a branch`);

      // 変換しない正準segmentを使い入力順を保ったまま既存ノードを再利用する
      // Reuse nodes by canonical segment without conversion while preserving input order
      let child = node.childrenBySegment.get(segment);
      if (!child) {
        const fullKey = node === root ? segment : `${node.fullKey}.${segment}`;
        child = createNode(segment, fullKey);
        node.children.push(child);
        node.childrenBySegment.set(segment, child);
      }
      node = child;
    }

    if (node.children.length > 0) throw new Error(`Key '${node.fullKey}' is both a leaf and a branch`);
    node.isLeaf = true;
  }
  return root;
}

function createNode(segment, fullKey) {
  return { segment, fullKey, children: [], childrenBySegment: new Map(), isLeaf: false };
}

function validateKeySegment(segment, fullKey) {
  if (!KEY_SEGMENT_PATTERN.test(segment)) {
    throw new Error(
      `Localization key segment '${segment}' in key '${fullKey}' must match [a-z][A-Za-z0-9]*`,
    );
  }
}

function emitObject(children) {
  const members = children.map((node) => {
    const value = node.isLeaf ? JSON.stringify(node.fullKey) : emitObject(node.children);
    return `${node.segment}: ${value}`;
  });
  return `{${members.join(", ")}}`;
}

function convertEscapedNewlines(text) {
  return text.replaceAll("\\n", "\n");
}

const isCli = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isCli) {
  const csvUrl = new URL("../../../Localization/localization.csv", import.meta.url);
  const outputUrl = new URL("../src/shared/i18n/generated/localizationKeys.ts", import.meta.url);
  mkdirSync(new URL("../src/shared/i18n/generated/", import.meta.url), { recursive: true });
  const csv = parseLocalizationCsv(readFileSync(csvUrl, "utf8"));
  writeFileSync(outputUrl, generateLocalizationKeysSource(csv));
}
